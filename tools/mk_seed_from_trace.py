#!/usr/bin/env python3
"""Seed data of the local server from a recorded session (documentation/protocol.md).

Takes from work/real/<trace>/ only what the real servers simply STORE (reference content): Iris assets, the AH server config, the
live-ops event templates, the CRM config and the profile template of a new player. Everything per player/session (tokens, ids,
hashes, addresses, times) is generated by server/mc5 itself (documentation/protocol.md: the recording is the specification, not the answers).

Output: server/data/iris/<asset>, server/data/ah/{config.bin,new_profile.json,events.json,crm.json,meta.json}
Run:    .venv/bin/python -I tools/mk_seed_from_trace.py [work/real/trace] [--iris-only]
"""
import json
import os
import sys
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "server"))
from mc5 import lz4, ahproto  # noqa: E402

ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
IRIS_ONLY = "--iris-only" in sys.argv   # add Iris assets of another recording without touching the AH seed
TRACE = ARGS[0] if ARGS else os.path.join(ROOT, "work", "real", "trace")
OUT = os.path.join(ROOT, "server", "data")
IRIS_CDN = "iris06-gold-ssl.gameloft.com"


def iris_assets():
    """Iris answers 302 to the CDN; the asset name is the one the client asked Iris for (Location -> name), the CDN GET carries the body."""
    os.makedirs(os.path.join(OUT, "iris"), exist_ok=True)
    rows = [json.loads(line) for line in open(os.path.join(TRACE, "http.jsonl"))]
    name_of = {}
    for r in rows:
        u = urllib.parse.urlsplit(r["url"])
        if u.netloc.startswith("iris.") and r.get("status") == 302 and "/assets/" in u.path:
            hdr = r["resp_headers"] if isinstance(r["resp_headers"], list) else list(r["resp_headers"].items())
            loc = next((v for k, v in hdr if k.lower() == "location"), None)
            if loc:
                name_of[urllib.parse.urlsplit(loc).path] = urllib.parse.unquote(u.path).split("/")[-1]
    got = {}
    for r in rows:
        u = urllib.parse.urlsplit(r["url"])
        if u.netloc != IRIS_CDN or r["method"] != "GET" or r["status"] != 200:
            continue
        name = name_of.get(u.path) or urllib.parse.unquote(u.path).split("/")[-1].rsplit("_", 1)[0]
        if name.startswith("bald_"):
            continue  # BALD service files come from the BALD store (work/bald6012)
        body = r["resp_body"]
        if isinstance(body, dict) and body.get("file"):          # bodies over 1 MB are stored next to the trace
            data = open(os.path.join(TRACE, body["file"]), "rb").read()
        else:
            data = body.encode("latin1") if isinstance(body, str) else bytes(body)
        got[name] = data
    for name, data in got.items():
        with open(os.path.join(OUT, "iris", name), "wb") as f:
            f.write(data)
        print("iris  %-70s %8d" % (name, len(data)))


def first_ah_connection():
    """The first AH connection of the trace with the full first-login sequence (`01` with 0, `I`, `t`)."""
    evs = []
    for line in open(os.path.join(TRACE, "tcp.jsonl")):
        r = json.loads(line)
        if r["kind"] != "ah":
            continue
        if r.get("event") == "eof":
            if evs:
                break
            continue
        evs.append((r["dir"], bytes.fromhex(r["hex"])))
    out = {"c2s": [], "s2c": []}
    for d in out:
        buf = b"".join(b for dd, b in evs if dd == d)
        out[d] = list(ahproto.split_frames(buf))
    return out


def ah_seed():
    os.makedirs(os.path.join(OUT, "ah"), exist_ok=True)
    conn = first_ah_connection()
    meta = {"source": os.path.relpath(TRACE, ROOT)}
    for t, payload in conn["s2c"]:
        if t == 0x23 and "config" not in meta:
            open(os.path.join(OUT, "ah", "config.bin"), "wb").write(payload)
            meta["config"] = len(payload)
        elif t == 0x4F and "seed_time" not in meta:
            meta["seed_time"] = int.from_bytes(payload[:4], "big")
        elif t == 0x27 and "profile" not in meta:
            prof = json.loads(lz4.unpack_sized(payload))
            json.dump(prof, open(os.path.join(OUT, "ah", "new_profile.json"), "w"), ensure_ascii=False, indent=1)
            meta["profile"] = sorted(prof)
        elif t == 0x28 and "events" not in meta:
            ev = json.loads(lz4.unpack_sized(payload[1:]))
            json.dump(ev, open(os.path.join(OUT, "ah", "events.json"), "w"), ensure_ascii=False, indent=1)
            meta["events"] = [e["name"] for e in ev]
        elif t == 0x3F and "crm" not in meta:
            crm = json.loads(lz4.unpack_sized(payload).rstrip(b"\0"))
            json.dump(crm, open(os.path.join(OUT, "ah", "crm.json"), "w"), ensure_ascii=False)
            meta["crm"] = sorted(crm)
        elif t == 0x47 and "offers" not in meta:
            n = int.from_bytes(payload[4:8], "big")
            offers = json.loads(payload[8:8 + n])
            meta["offers"] = [o["name"] for o in offers["offers"]]
    json.dump(meta, open(os.path.join(OUT, "ah", "meta.json"), "w"), ensure_ascii=False, indent=1)
    print("ah   ", json.dumps({k: (v if not isinstance(v, list) else len(v)) for k, v in meta.items()}))


if __name__ == "__main__":
    iris_assets()
    if not IRIS_ONLY:
        ah_seed()
